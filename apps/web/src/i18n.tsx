function interpolate(message: string, values?: Values) {
  if (!values) return message
  return Object.entries(values).reduce((text, [key, value]) => text.replaceAll(`{${key}}`, String(value)), message)
}

type I18n = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, values?: Values) => string
  date: (value: Date | number | string, options?: Intl.DateTimeFormatOptions) => string
}

const I18nContext = createContext<I18n | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => loadPrefs().locale)
  const value = useMemo<I18n>(() => ({
    locale,
    setLocale(next) {
      savePrefs({ locale: next })
      setLocaleState(next)
    },
    t(key, values) {
      return interpolate(locale === "zh-CN" ? (zhCN[key] ?? key) : key, values)
    },
    date(input, options) {
      return new Intl.DateTimeFormat(locale, options).format(new Date(input))
    },
  }), [locale])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error("useI18n must be used inside I18nProvider")
  return value
}
